#!/usr/bin/env python3
"""Read make-fixtures.js's "VFX FIXTURE <name> <json>" lines on stdin and write tests/fixtures/ (see make-fixtures.js)."""
import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "fixtures")
os.makedirs(OUT, exist_ok=True)
got = {}
for line in sys.stdin:
    if not line.startswith("VFX FIXTURE "):
        continue
    _, _, name, payload = line.rstrip("\n").split(" ", 3)
    got[name] = json.loads(payload)
if "done" not in got:
    sys.exit("fixtures failed: no done line")
# the project file exactly as Save project wrote it, the My Effects file as ⬇ wrote it, the rest as one JS file
with open(os.path.join(OUT, "head-project.crunchyvfx"), "w", encoding="utf-8") as fh:
    fh.write(got["project"]["file"])
with open(os.path.join(OUT, "head-effects.json"), "w", encoding="utf-8") as fh:
    fh.write(got["effectsFile"]["file"])
with open(os.path.join(OUT, "head.js"), "w", encoding="utf-8") as fh:
    fh.write("// GENERATED by tests/make-fixtures.js on CrunchyVFX HEAD 11e8d14 (before the planted Library): never edit by hand.\n")
    fh.write("window.VFX_HEAD = " + json.dumps(got, ensure_ascii=True, indent=1) + ";\n")
print("wrote", OUT, sorted(got))
